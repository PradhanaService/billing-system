"""Builds src/Components/PhosphorIcons.cs from the Phosphor Icons package (https://phosphoricons.com, MIT).

Run when icons are added or changed:
    npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
    python3 tools/phosphor_icons.py package
The app's own icon names (left) map to Phosphor icon names (right). Each icon is stored in two
styles: "regular" (outline) and "duotone" (outline with a soft fill), as plain SVG paths.
"""
import re, sys, pathlib

ICONS = {
    # menu and page headers
    "home": "squares-four", "users": "users-three", "truck": "truck", "layers": "books",
    "file-text": "invoice", "table": "table", "receipt-in": "hand-deposit", "payment-out": "hand-withdraw",
    "chart": "chart-bar", "key": "key", "badge": "identification-badge", "activity": "pulse",
    "database": "database", "trash": "trash",
    # figures, forms and buttons
    "droplet": "drop", "user": "user", "building": "buildings", "book": "book-open", "calendar": "calendar-blank",
    "shield": "shield-check", "recovery": "arrow-counter-clockwise", "restore": "clock-counter-clockwise",
    "rupee": "currency-inr", "cash": "money", "card": "credit-card", "clock": "clock", "wallet": "wallet",
    "zap": "lightning", "logout": "sign-out", "chevron-down": "caret-down", "chevron-left": "caret-left",
    "chevron-right": "caret-right", "alert": "warning-circle", "x": "x", "edit": "pencil-simple", "eye": "eye",
    "printer": "printer", "search": "magnifying-glass", "check": "check", "folder": "folder-open", "plus": "plus",
    "lock": "lock", "download": "download-simple", "upload": "upload-simple", "save": "floppy-disk",
    "file-pdf": "file-pdf", "meter": "gauge",
}

def inner(svg: str) -> str:
    body = re.sub(r"^<svg[^>]*>|</svg>\s*$", "", svg.strip())
    return body.replace('"', '\\"')

root = pathlib.Path(sys.argv[1]) / "assets"
lines = []
for style, suffix in (("Regular", ""), ("Duotone", "-duotone")):
    lines.append(f"    public static readonly IReadOnlyDictionary<string, string> {style} = new Dictionary<string, string>\n    {{")
    for name, ph in ICONS.items():
        svg = (root / style.lower() / f"{ph}{suffix}.svg").read_text()
        lines.append(f'        ["{name}"] = "{inner(svg)}",   // {ph}')
    lines.append("    };\n")

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "Components" / "PhosphorIcons.cs"
out.write_text(
    "// GENERATED by tools/phosphor_icons.py from Phosphor Icons 2.1.1 (https://phosphoricons.com).\n"
    "// Phosphor Icons: MIT License, Copyright (c) 2023 Phosphor Icons. See THIRD-PARTY-NOTICES.md.\n"
    "// Do not edit by hand: change the list in the script and run it again.\n"
    "namespace WaterBilling.Components;\n\n"
    "public static class PhosphorIcons\n{\n" + "\n".join(lines) + "}\n")
print(f"wrote {out} ({len(ICONS)} icons x 2 styles)")
